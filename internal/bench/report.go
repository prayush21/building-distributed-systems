package bench

import (
	"fmt"
	"strings"
)

// Markdown renders a report as a markdown document.
func Markdown(rep *Report) string {
	var b strings.Builder
	w := func(format string, args ...any) {
		fmt.Fprintf(&b, format+"\n", args...)
	}

	w("# Cache policy benchmark\n")
	w("Generated by `cmd/bench`. Do not edit by hand.\n")

	w("## Configuration\n")
	w("| | |")
	w("|---|---|")
	w("| Policies | %s |", strings.Join(backticked(rep.Config.Policies), ", "))
	w("| Cache sizes | %s |", strings.Join(backticked(rep.Config.Sizes), ", "))
	w("| Traces | %d |", len(rep.Traces))
	w("| Object sizes | %s |", ternary(rep.Config.IgnoreObjSize,
		"ignored, cache sizes are object counts (`--ignore-obj-size`)",
		"honored, cache sizes are bytes"))
	w("| Warmup | %s |", ternary(rep.Config.WarmupFrac > 0,
		fmt.Sprintf("first %.0f%% of each trace, excluded from metrics", rep.Config.WarmupFrac*100),
		"none"))
	w("| Seed | %d |", rep.Config.Seed)
	w("| Belady baseline | %s |", ternary(rep.Config.Oracle, "enabled", "**disabled**, gap-closed unavailable"))
	if rep.Config.Command != "" {
		w("")
		w("Reproduce with:\n")
		w("```")
		w("%s", rep.Config.Command)
		w("```")
	}
	w("")

	w("## Traces\n")
	w("| trace | requests | unique objects | working set |")
	w("|---|---:|---:|---:|")
	for _, t := range rep.Traces {
		w("| `%s` | %s | %s | %s |", t.Name,
			commas(t.Requests), commas(t.UniqueObjects), bytesHuman(t.WorkingSetBytes))
	}
	w("")

	w("## Summary across traces\n")
	w("Raw miss ratios are not comparable across traces, so the two derived")
	w("columns carry the comparison. Reduction is measured against FIFO, which")
	w("normalizes each trace against its own weakest baseline. Gap closed is")
	w("measured against the LRU-to-Belady interval, which states how much of the")
	w("headroom actually available on that workload was captured.\n")
	w("Medians are given alongside means because one trace with a narrow")
	w("LRU-to-OPT gap can move a mean a long way without saying much.\n")

	w("| policy | size | traces | mean miss ratio | reduction vs FIFO (mean) | (median) | gap closed vs OPT (mean) | (median) |")
	w("|---|---|---:|---:|---:|---:|---:|---:|")
	for _, s := range rep.Summary {
		note := ""
		if s.Failures > 0 {
			note = fmt.Sprintf(" ⚠%d", s.Failures)
		}
		w("| `%s` | %s | %d%s | %.4f | %s | %s | %s | %s |",
			s.Policy, s.SizeSpec, s.Traces, note, s.MeanMissRatio,
			pct(s.MeanReductionVsFIFO), pct(s.MedianReductionVsFIFO),
			pct(s.MeanGapClosed), pct(s.MedianGapClosed))
	}
	w("")

	w("## Per trace\n")
	for _, t := range rep.Traces {
		w("### `%s`\n", t.Name)
		w("| size | policy | request MR | byte MR | reduction vs FIFO | gap closed vs OPT | evictions | metadata B/obj | ns/op |")
		w("|---|---|---:|---:|---:|---:|---:|---:|---:|")
		for _, sizeSpec := range rep.Config.Sizes {
			for _, c := range rep.Results {
				if c.Trace != t.Name || c.SizeSpec != sizeSpec {
					continue
				}
				if c.Error != "" {
					w("| %s | `%s` | — | — | — | — | — | — | — |  <!-- %s -->",
						c.SizeSpec, c.Policy, c.Error)
					continue
				}
				w("| %s (%s) | `%s` | %.6f | %.6f | %s | %s | %s | %.1f | %.0f |",
					c.SizeSpec, bytesHuman(c.SizeBytes), c.Policy,
					c.RequestMissRatio, c.ByteMissRatio,
					pct(c.MRReductionVsFIFO), pct(c.GapClosedVsBelady),
					commas(c.Evictions), c.MetadataBytesPerResidentObject,
					c.NanosecondsPerOp)
			}
		}
		w("")
	}

	if len(rep.Skipped) > 0 {
		w("## Traces that could not be read\n")
		w("| path | reason |")
		w("|---|---|")
		for _, s := range rep.Skipped {
			w("| `%s` | %s |", s.Path, s.Reason)
		}
		w("")
	}

	if errs := failures(rep); len(errs) > 0 {
		w("## Configurations that did not run\n")
		w("| trace | size | policy | reason |")
		w("|---|---|---|---|")
		for _, c := range errs {
			w("| `%s` | %s | `%s` | %s |", c.Trace, c.SizeSpec, c.Policy, c.Error)
		}
		w("")
	}

	w("## Reading these numbers\n")
	w("- **Reduction vs FIFO** is `(FIFO_mr - policy_mr) / FIFO_mr`. Positive is")
	w("  better. FIFO's own row is 0 by construction.")
	w("- **Gap closed vs OPT** is `(LRU_mr - policy_mr) / (LRU_mr - OPT_mr)`. LRU")
	w("  is 0 and Belady is 100%% by construction. Negative means worse than LRU.")
	w("- **Above 100%% is possible and is not a bug.** Belady is provably optimal")
	w("  only when every object is the same size; with variable sizes, optimal")
	w("  offline caching is NP-hard and the Belady baseline is a strong upper")
	w("  bound rather than a true ceiling. Under `--ignore-obj-size` it is a true")
	w("  ceiling and values should not exceed 100%%.")
	w("- **`—`** means undefined, not zero: either the run failed, or the")
	w("  denominator was too small to divide by. Gap closed is withheld when the")
	w("  LRU-to-OPT gap is under %g, where the ratio would be noise.", minGapForRatio)
	w("- **ns/op** is measured over the in-memory replay loop, so it reflects the")
	w("  policy rather than trace parsing. It is still a wall-clock measurement")
	w("  on a shared machine and should be read as a rough cost, not a benchmark.")
	return b.String()
}

func failures(rep *Report) []Cell {
	var out []Cell
	for _, c := range rep.Results {
		if c.Error != "" {
			out = append(out, c)
		}
	}
	return out
}

// pct formats a ratio as a percentage, or an em dash when undefined. An
// undefined value must never render as 0: they mean different things.
func pct(v *float64) string {
	if v == nil {
		return "—"
	}
	return fmt.Sprintf("%+.1f%%", *v*100)
}

func backticked(xs []string) []string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = "`" + x + "`"
	}
	return out
}

func ternary(cond bool, yes, no string) string {
	if cond {
		return yes
	}
	return no
}

func commas(n int64) string {
	s := fmt.Sprintf("%d", n)
	if n < 0 {
		return "-" + commas(-n)
	}
	var parts []string
	for len(s) > 3 {
		parts = append([]string{s[len(s)-3:]}, parts...)
		s = s[:len(s)-3]
	}
	return strings.Join(append([]string{s}, parts...), ",")
}

func bytesHuman(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for m := n / unit; m >= unit && exp < 4; m /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", float64(n)/float64(div), "KMGTP"[exp])
}
